-- 4.20 合并冗余查询：一次查询同时获取"用户总数 + 正常用户数 + 禁用用户数"
-- 用途：仪表盘一次性返回多维度统计，替代原 4.11 + 4.12 三次独立查询
-- 【优化点】利用带条件的 SUM 聚合，单次扫描同时产出三个指标，减少 2/3 的查询往返；
