-- ============================================================
-- 文件名称：user_op_up.sql
-- 功能描述：user 用户表的增删改查（CRUD）操作脚本【优化版】
-- 依赖对象：AIcode 数据库下的 user 表（由 user.sql 创建）
-- 索引清单：
--   PRIMARY KEY (id)
--   uk_user_username           (username)              唯一索引
--   idx_user_role_id           (role_id)               普通索引
--   idx_user_is_disabled       (is_disabled)           普通索引
--   idx_user_role_disabled     (role_id, is_disabled)  复合索引
-- 优化方向：
--   1) 索引利用优化（避免函数包裹列、隐式类型转换、左模糊 LIKE）
--   2) 分页查询优化（大偏移量改用游标 / 延迟关联写法）
--   3) 查询字段精简（避免 SELECT *，按需投影）
--   4) 条件下推与覆盖索引利用
--   5) 排序优化（利用索引有序性避免 filesort）
--   6) 合并冗余查询
-- 备注说明：所有 SQL 均针对 `AIcode`.`user` 表，每条语句均标注【优化点】
-- ============================================================

-- 切换到目标数据库
USE `AIcode`;

-- ============================================================
-- 一、插入操作（Create）
-- ============================================================

-- ------------------------------------------------------------
-- 1.1 单条插入：新增一个用户（指定全部业务字段）
-- 用途：注册新用户时使用，用户名必须唯一否则违反唯一索引
-- 注意：password 字段应传入加密后的密文，不应存明文
-- 【优化点】显式列出字段列表，避免依赖列顺序；冲突时由 uk_user_username 唯一索引快速判定
-- ------------------------------------------------------------
INSERT INTO `user` (
    `avatar`,
    `username`,
    `password`,
    `preference`,
    `role_id`,
    `is_disabled`
) VALUES (
    'https://example.com/avatar/default.png',  -- 用户头像URL
    'zhangsan',                                 -- 用户名（唯一）
    '$2a$10$xxxxxxxxxxxxxxxxxxxxxxxxxxxx',      -- 密码密文（bcrypt 示例）
    '{"theme":"dark","lang":"zh-CN"}',          -- 用户喜好（JSON 字符串）
    1,                                          -- 角色ID
    0                                           -- 是否禁用：0-正常
);

-- ------------------------------------------------------------
-- 1.2 单条插入：仅必填字段（用户名 + 密码）
-- 用途：最小化注册场景，其余字段使用表默认值
-- 【优化点】仅写入必填字段，其余走表默认值，减少 binlog/redo 体积
-- ------------------------------------------------------------
INSERT INTO `user` (`username`, `password`)
VALUES ('lisi', 'encrypted_password_here');     -- 用户名、密码密文

-- ------------------------------------------------------------
-- 1.3 单条插入并返回自增主键
-- 用途：插入后需立即获取新用户ID（如关联写入其他表）
-- 【优化点】使用 LAST_INSERT_ID() 基于当前会话连接获取，无需再次查询 user 表，避免一次主键回查
-- ------------------------------------------------------------
INSERT INTO `user` (`username`, `password`, `role_id`)
VALUES ('wangwu', 'encrypted_password_here', 2);

-- 获取刚刚插入的自增主键ID（与上一条 INSERT 配合使用，走会话上下文，无表扫描）
SELECT LAST_INSERT_ID() AS `new_user_id`;

-- ------------------------------------------------------------
-- 1.4 批量插入：一次性新增多个用户
-- 用途：批量导入用户、初始化测试数据
-- 注意：任一 username 重复都会导致整批失败，建议事先校验或使用事务
-- 【优化点】单条多 VALUES 批量插入，比循环单条 INSERT 减少 N-1 次提交与索引维护开销；
--          命中 uk_user_username 唯一索引做冲突检测
-- ------------------------------------------------------------
INSERT INTO `user` (
    `avatar`,
    `username`,
    `password`,
    `preference`,
    `role_id`,
    `is_disabled`
) VALUES
    ('https://example.com/avatar/u1.png', 'user001', 'pwd_encrypted_1', NULL, 0, 0),
    ('https://example.com/avatar/u2.png', 'user002', 'pwd_encrypted_2', NULL, 0, 0),
    ('https://example.com/avatar/u3.png', 'user003', 'pwd_encrypted_3', '{"theme":"light"}', 3, 0),
    (NULL,                                  'user004', 'pwd_encrypted_4', NULL, 0, 1);

-- ------------------------------------------------------------
-- 1.5 插入或忽略：用户名已存在则跳过
-- 用途：批量导入时避免因重复用户名中断整批插入
-- 【优化点】INSERT IGNORE 命中 uk_user_username 唯一键冲突时静默跳过，无需先 SELECT 再判断
-- ------------------------------------------------------------
INSERT IGNORE INTO `user` (`username`, `password`, `role_id`)
VALUES ('zhangsan', 'pwd_encrypted_new', 1);    -- 若 zhangsan 已存在则忽略

-- ------------------------------------------------------------
-- 1.6 插入或更新：用户名已存在则更新指定字段
-- 用途：upsert 场景，按 username 唯一键冲突时更新密码、头像、喜好等
-- 【优化点】ON DUPLICATE KEY UPDATE 基于 uk_user_username 唯一键定位冲突行，
--          一次操作完成"存在性判定 + 插入/更新"，避免"先 SELECT 再 INSERT/UPDATE"两次交互
-- ------------------------------------------------------------
INSERT INTO `user` (`username`, `password`, `avatar`, `preference`, `role_id`)
VALUES ('zhangsan', 'pwd_encrypted_new', 'https://example.com/avatar/new.png', '{"theme":"dark"}', 2)
ON DUPLICATE KEY UPDATE
    `password`   = VALUES(`password`),          -- 更新为待插入的密码
    `avatar`     = VALUES(`avatar`),            -- 更新为待插入的头像
    `preference` = VALUES(`preference`),        -- 更新为待插入的喜好
    `role_id`    = VALUES(`role_id`);           -- 更新为待插入的角色ID


-- ============================================================
-- 二、删除操作（Delete）
-- ============================================================

-- ------------------------------------------------------------
-- 2.1 按主键删除：删除指定ID的用户
-- 用途：根据用户ID删除单个用户
-- 注意：生产环境建议改为"软删除"（更新 is_disabled=1），物理删除需谨慎
-- 【优化点】WHERE id = 常量命中主键索引，O(1) 定位行
-- ------------------------------------------------------------
DELETE FROM `user`
WHERE `id` = 1;                                 -- 待删除的用户主键ID

-- ------------------------------------------------------------
-- 2.2 按主键批量删除：删除多个指定ID的用户
-- 用途：批量删除用户（如后台管理勾选多个用户后批量删除）
-- 【优化点】IN 列表走主键索引多次定位，避免逐条 DELETE 的往返开销；
--          IN 列表元素类型须为整型，避免与 BIGINT 主键发生隐式类型转换导致索引失效
-- ------------------------------------------------------------
DELETE FROM `user`
WHERE `id` IN (10, 11, 12, 13, 14);             -- 待删除的用户主键ID列表

-- ------------------------------------------------------------
-- 2.3 按用户名删除：删除指定用户名的用户
-- 用途：按登录账号删除用户
-- 【优化点】WHERE username = 常量命中 uk_user_username 唯一索引，等值精确匹配，无类型转换
-- ------------------------------------------------------------
DELETE FROM `user`
WHERE `username` = 'zhangsan';                  -- 待删除的用户名

-- ------------------------------------------------------------
-- 2.4 按条件删除：删除某角色下所有已禁用用户
-- 用途：清理某角色下被禁用的账号
-- 【优化点】(role_id, is_disabled) 双等值条件精确命中复合索引 idx_user_role_disabled，
--          无需回表即可定位待删行；执行前建议先用 SELECT 确认影响范围
-- ------------------------------------------------------------
DELETE FROM `user`
WHERE `role_id` = 3                              -- 指定角色ID
  AND `is_disabled` = 1;                         -- 且已被禁用

-- ------------------------------------------------------------
-- 2.5 按条件删除：删除创建时间早于指定日期的所有用户
-- 用途：清理历史脏数据或过期账号
-- 注意：执行前建议先用 SELECT 确认影响范围
-- 【优化点/风险】create_time 无索引，该删除为全表扫描 + 范围过滤，数据量大时锁面较广；
--               建议分批删除（按 id 分片）或为 create_time 增加索引；此处保留原语义并标注风险
-- ------------------------------------------------------------
DELETE FROM `user`
WHERE `create_time` < '2020-01-01 00:00:00';    -- 创建时间早于该时间点的用户

-- ------------------------------------------------------------
-- 2.6 清空全表（慎用）
-- 用途：仅用于测试环境重置数据，生产环境严禁使用
-- 注意：TRUNCATE 会重置 AUTO_INCREMENT，且无法事务回滚
-- ------------------------------------------------------------
-- TRUNCATE TABLE `user`;                       -- 取消注释后执行，将清空全部用户数据


-- ============================================================
-- 三、修改操作（Update）
-- ============================================================

-- ------------------------------------------------------------
-- 3.1 按主键修改：更新指定用户的基本信息
-- 用途：编辑用户资料（头像、喜好、角色）
-- 注意：update_time 由 ON UPDATE 自动维护，无需手动赋值
-- 【优化点】WHERE id = 常量命中主键索引，行级锁仅锁目标行；仅 SET 必要字段，避免无谓字段写入
-- ------------------------------------------------------------
UPDATE `user`
SET `avatar`     = 'https://example.com/avatar/new.png',  -- 新头像URL
    `preference` = '{"theme":"dark","lang":"en"}',        -- 新喜好设置
    `role_id`    = 2                                       -- 新角色ID
WHERE `id` = 1;                                            -- 目标用户主键ID

-- ------------------------------------------------------------
-- 3.2 按主键修改密码：更新指定用户的密码
-- 用途：用户修改密码 / 管理员重置密码
-- 注意：应传入加密后的密文
-- 【优化点】命中主键索引；仅更新 password 单字段，最小化 binlog 体积
-- ------------------------------------------------------------
UPDATE `user`
SET `password` = '$2a$10$yyyyyyyyyyyyyyyyyyyyyyyy'        -- 新密码密文
WHERE `id` = 1;                                            -- 目标用户主键ID

-- ------------------------------------------------------------
-- 3.3 按主键修改状态：禁用 / 启用指定用户
-- 用途：管理员封禁或解封用户账号
-- 【优化点】命中主键索引；is_disabled 为 TINYINT(1)，赋值 0/1 整型字面量，无隐式类型转换
-- ------------------------------------------------------------
UPDATE `user`
SET `is_disabled` = 1                                      -- 1-禁用，0-启用
WHERE `id` = 1;                                            -- 目标用户主键ID

-- ------------------------------------------------------------
-- 3.4 按主键批量修改状态：批量禁用多个用户
-- 用途：后台批量封禁
-- 【优化点】IN 列表走主键索引；元素为整型，避免隐式类型转换导致主键索引失效
-- ------------------------------------------------------------
UPDATE `user`
SET `is_disabled` = 1                                      -- 1-禁用
WHERE `id` IN (10, 11, 12);                                -- 目标用户主键ID列表

-- ------------------------------------------------------------
-- 3.5 按条件修改：将某角色下所有用户切换到新角色
-- 用途：角色调整 / 权限迁移
-- 【优化点】(role_id, is_disabled) 等值条件命中复合索引 idx_user_role_disabled，
--          索引范围内直接定位待更新行；注意更新 role_id 会触发 idx_user_role_id / idx_user_role_disabled 索引维护
-- ------------------------------------------------------------
UPDATE `user`
SET `role_id` = 5                                          -- 新角色ID
WHERE `role_id` = 3                                        -- 原角色ID
  AND `is_disabled` = 0;                                   -- 仅更新正常用户

-- ------------------------------------------------------------
-- 3.6 按条件修改：禁用某时间点之前注册的用户
-- 用途：长期未活跃账号批量封禁
-- 【优化点】优先以 is_disabled = 0 等值条件下推命中 idx_user_is_disabled 过滤候选集，
--          再回表判断 create_time 范围；create_time 无索引，回表范围过滤不可避免，建议分批提交避免大事务
-- ------------------------------------------------------------
UPDATE `user`
SET `is_disabled` = 1                                      -- 1-禁用
WHERE `create_time` < '2023-01-01 00:00:00'                -- 创建时间早于该时间点
  AND `is_disabled` = 0;                                   -- 且当前为正常状态

-- ------------------------------------------------------------
-- 3.7 按用户名修改头像：根据用户名更新头像
-- 用途：用户在前台自行更换头像
-- 【优化点】WHERE username = 常量命中 uk_user_username 唯一索引，等值精确匹配，O(1) 定位
-- ------------------------------------------------------------
UPDATE `user`
SET `avatar` = 'https://example.com/avatar/updated.png'    -- 新头像URL
WHERE `username` = 'zhangsan';                             -- 目标用户名


-- ============================================================
-- 四、查询操作（Read）
-- ============================================================

-- ------------------------------------------------------------
-- 4.1 单条查询：按主键ID查询用户全部字段
-- 用途：根据用户ID获取用户详细信息
-- 【优化点】原 SELECT * 改为按需投影，避免回表读取冗余列（preference 等）；
--          WHERE id = 常量命中主键索引，O(1) 定位
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `password`,
       `role_id`,
       `is_disabled`,
       `create_time`,
       `update_time`
FROM `user`
WHERE `id` = 1;                                            -- 目标用户主键ID

-- ------------------------------------------------------------
-- 4.2 单条查询：按用户名查询用户（登录校验场景）
-- 用途：登录时根据用户名获取账号信息（含密码密文用于比对）
-- 【优化点】命中 uk_user_username 唯一索引，等值匹配；按需投影避免 SELECT *；
--          唯一索引已保证最多一行，LIMIT 1 仅作防御性写法
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `password`,
       `avatar`,
       `role_id`,
       `is_disabled`,
       `create_time`,
       `update_time`
FROM `user`
WHERE `username` = 'zhangsan'                              -- 登录用户名
LIMIT 1;                                                   -- 防御性限制单条

-- ------------------------------------------------------------
-- 4.3 单条查询：仅返回用户ID是否存在（存在性校验）
-- 用途：注册时校验用户名是否已被占用
-- 【优化点】SELECT 1 + LIMIT 1 走 uk_user_username 唯一索引，命中即返回，不读取实际列数据；
--          相比 SELECT id 仍是覆盖索引扫描（二级索引叶子节点存主键），但 SELECT 1 语义更清晰、避免列解析
-- ------------------------------------------------------------
SELECT 1 AS `is_exists`
FROM `user`
WHERE `username` = 'zhangsan'                              -- 待校验的用户名
LIMIT 1;

-- ------------------------------------------------------------
-- 4.4 列表查询：查询全部用户（带返回字段裁剪）
-- 用途：用户管理列表页展示
-- 注意：生产环境应避免无 LIMIT 的全表查询，此处仅作示例
-- 【优化点】按需投影避免 SELECT *；ORDER BY id ASC 走主键天然有序，无 filesort；
--          建议生产环境强制追加 LIMIT 分页（参见 4.6）
-- ------------------------------------------------------------
SELECT `id`,
       `avatar`,
       `username`,
       `role_id`,
       `is_disabled`,
       `create_time`
FROM `user`
ORDER BY `id` ASC;                                         -- 按主键升序排列（走主键有序，无 filesort）

-- ------------------------------------------------------------
-- 4.5 列表查询：查询所有正常（未禁用）用户
-- 用途：获取有效账号列表
-- 【优化点】WHERE is_disabled = 0 等值条件下推命中 idx_user_is_disabled 过滤；
--          【风险】ORDER BY create_time DESC 因 create_time 无索引，过滤后仍需 filesort；
--          建议为 (is_disabled, create_time) 建复合索引以消除 filesort，或改用 ORDER BY id（业务允许时）
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `role_id`,
       `create_time`
FROM `user`
WHERE `is_disabled` = 0                                    -- 0-正常（命中 idx_user_is_disabled）
ORDER BY `create_time` DESC;                               -- ⚠ filesort 风险：create_time 无索引

-- ------------------------------------------------------------
-- 4.6 分页查询：按页码查询用户列表（游标分页优化版）
-- 用途：后台分页展示用户列表
-- 参数说明：last_id 为上一页最后一条记录的 id（首页传 0），page_size 为每页条数
-- 【优化点】原 LIMIT 10 OFFSET 10 在大偏移量下需扫描 offset+limit 行，深度分页性能劣化；
--          改用游标分页 WHERE id > last_id ORDER BY id ASC LIMIT page_size，命中主键索引范围扫描，
--          无论翻到第几页都只扫描 page_size 行，O(page_size) 复杂度；
--          示例：首页 last_id=0 取 10 条 → 假设末条 id=10，下一页 last_id=10
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `role_id`,
       `is_disabled`,
       `create_time`
FROM `user`
WHERE `id` > 0                                             -- 游标：上一页末尾 id（首页传 0）
ORDER BY `id` ASC                                          -- 按主键升序（走主键有序，无 filesort）
LIMIT 10;                                                  -- 每页 10 条

-- ------------------------------------------------------------
-- 4.6b 分页查询：大偏移量延迟关联写法（兼容必须按 OFFSET 翻页的场景）
-- 用途：业务上无法改用游标分页（如支持任意页码跳转）时的深度分页兜底方案
-- 【优化点】先在子查询中仅凭主键索引定位目标页的主键集合（覆盖索引扫描，不回表），
--          再外层关联回表取所需字段，避免"OFFSET 扫描 + 回表取全部列"的双重代价；
--          示例：第 1000 页，每页 10 条 → OFFSET 9990
-- ------------------------------------------------------------
SELECT u.`id`,
       u.`username`,
       u.`avatar`,
       u.`role_id`,
       u.`is_disabled`,
       u.`create_time`
FROM `user` u
INNER JOIN (
    SELECT `id`
    FROM `user`
    ORDER BY `id` ASC                                      -- 走主键索引有序
    LIMIT 10 OFFSET 9990                                   -- 子查询仅取主键，覆盖索引扫描
) t ON u.`id` = t.`id`
ORDER BY u.`id` ASC;

-- ------------------------------------------------------------
-- 4.7 分页查询：按条件分页查询某角色下的正常用户
-- 用途：角色管理页中查看某角色下的用户（分页）
-- 【优化点】(role_id, is_disabled) 双等值条件命中复合索引 idx_user_role_disabled 精确过滤；
--          首页 OFFSET 0 无深度分页问题；
--          【风险】ORDER BY create_time DESC 因 create_time 不在复合索引内，过滤后仍需 filesort；
--          建议为 (role_id, is_disabled, create_time) 建三列复合索引以消除 filesort
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `create_time`
FROM `user`
WHERE `role_id` = 2                                        -- 指定角色ID（命中复合索引前导列）
  AND `is_disabled` = 0                                    -- 仅正常用户（命中复合索引第二列）
ORDER BY `create_time` DESC                                -- ⚠ filesort 风险：create_time 不在索引内
LIMIT 20 OFFSET 0;                                         -- 每页20条，第1页

-- ------------------------------------------------------------
-- 4.8 条件查询：按用户名模糊查询（前缀匹配优化版）
-- 用途：后台搜索用户（支持用户名关键字检索）
-- 【优化点】原 LIKE '%zhang%' 左模糊导致 uk_user_username 索引失效退化为全表扫描；
--          改为前缀匹配 LIKE 'zhang%'（右模糊），可走 uk_user_username 索引范围扫描；
--          若业务确需双向模糊，建议引入全文索引（FULLTEXT）或外置 ES，避免大表全扫
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `role_id`,
       `is_disabled`
FROM `user`
WHERE `username` LIKE 'zhang%'                             -- 前缀匹配，命中 uk_user_username 范围扫描
ORDER BY `id` ASC
LIMIT 50;                                                  -- 限制最多返回50条

-- ------------------------------------------------------------
-- 4.9 条件查询：多条件组合查询（角色 + 状态 + 时间范围）
-- 用途：后台高级筛选用户
-- 【优化点】(role_id, is_disabled) 等值条件下推命中 idx_user_role_disabled 过滤候选集，
--          create_time 范围条件在回表后应用；
--          【风险】ORDER BY create_time DESC 仍需 filesort；
--          建议为 (role_id, is_disabled, create_time) 建复合索引，可使过滤+排序均走索引
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `role_id`,
       `is_disabled`,
       `create_time`,
       `update_time`
FROM `user`
WHERE `role_id` = 2                                        -- 指定角色ID（命中复合索引前导列）
  AND `is_disabled` = 0                                    -- 仅正常用户（命中复合索引第二列）
  AND `create_time` BETWEEN '2024-01-01 00:00:00'          -- 创建时间范围起（回表后过滤）
                           AND '2024-12-31 23:59:59'      -- 创建时间范围止
ORDER BY `create_time` DESC                                -- ⚠ filesort 风险
LIMIT 100;                                                 -- 限制最多返回100条

-- ------------------------------------------------------------
-- 4.10 条件查询：按用户ID集合批量查询
-- 用途：根据一批用户ID获取用户信息（如批量展示用户昵称头像）
-- 【优化点】IN 列表走主键索引多次等值定位；按需投影仅取 id/username/avatar 三列；
--          IN 元素须为整型，避免与 BIGINT 主键发生隐式类型转换导致索引失效
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`
FROM `user`
WHERE `id` IN (1, 2, 3, 5, 8, 13);                         -- 用户ID集合（整型，命中主键索引）

-- ------------------------------------------------------------
-- 4.11 聚合统计：统计用户总数
-- 用途：仪表盘展示用户总量
-- 【优化点/风险】InnoDB 下 COUNT(*) 需遍历聚簇索引估算/精确计数，无 WHERE 时无法利用二级索引加速；
--               建议高频场景维护独立计数表或使用 SHOW TABLE STATUS 近似值；此处保留原语义并标注风险
-- ------------------------------------------------------------
SELECT COUNT(*) AS `total_count`                           -- 用户总数
FROM `user`;

-- ------------------------------------------------------------
-- 4.12 聚合统计：按状态分组统计用户数量
-- 用途：统计正常 / 禁用用户数
-- 【优化点】GROUP BY is_disabled 走 idx_user_is_disabled 索引有序，避免临时表排序；
--          is_disabled 仅 0/1 两个分组，结果集极小
-- ------------------------------------------------------------
SELECT `is_disabled` AS `status`,                          -- 账号状态：0-正常，1-禁用
       COUNT(*)     AS `count`                             -- 对应数量
FROM `user`
GROUP BY `is_disabled`;                                    -- 命中 idx_user_is_disabled 有序，免临时表

-- ------------------------------------------------------------
-- 4.13 聚合统计：按角色分组统计用户数量
-- 用途：统计每个角色下的用户数
-- 【优化点】GROUP BY role_id 走 idx_user_role_id 索引有序，避免分组临时表排序；
--          ORDER BY user_count DESC 是对聚合结果排序，无法走索引，需对极小结果集做 filesort（代价可忽略）
-- ------------------------------------------------------------
SELECT `role_id`    AS `role_id`,                          -- 角色ID
       COUNT(*)    AS `user_count`                         -- 该角色下用户数
FROM `user`
GROUP BY `role_id`                                         -- 命中 idx_user_role_id 有序，免分组临时表
ORDER BY `user_count` DESC;                                -- 对聚合结果排序（结果集小，代价可忽略）

-- ------------------------------------------------------------
-- 4.14 聚合统计：按角色分组统计正常用户数量
-- 用途：统计每个角色下有效账号数
-- 【优化点】WHERE is_disabled = 0 等值过滤 + GROUP BY role_id；
--          优化器可选择 idx_user_role_id 按角色有序分组、回表过滤 is_disabled，
--          或选择 idx_user_is_disabled 过滤后再分组；MySQL 会基于选择性择优
-- ------------------------------------------------------------
SELECT `role_id`    AS `role_id`,                          -- 角色ID
       COUNT(*)    AS `active_count`                       -- 该角色下正常用户数
FROM `user`
WHERE `is_disabled` = 0                                    -- 仅统计正常用户
GROUP BY `role_id`;                                        -- 走 idx_user_role_id 有序分组

-- ------------------------------------------------------------
-- 4.15 排序查询：查询最近注册的 N 个用户
-- 用途：展示最新注册用户
-- 【优化点/风险】原 ORDER BY create_time DESC 因 create_time 无索引，需全表扫描 + filesort；
--               若业务上"注册顺序与 id 自增一致"，可改用 ORDER BY id DESC 走主键有序避免 filesort；
--               此处给出基于主键的等价改写版（语义：最近插入的用户）
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `create_time`
FROM `user`
ORDER BY `id` DESC                                         -- 改走主键有序（假设 id 自增≈注册顺序），免 filesort
LIMIT 10;                                                  -- 最近10个

-- ------------------------------------------------------------
-- 4.16 排序查询：查询最近更新的 N 个用户
-- 用途：展示近期有变更的用户
-- 【优化点/风险】ORDER BY update_time DESC 因 update_time 无索引，需全表扫描 + filesort；
--               建议为 update_time 增加索引以支持"最近变更"高频查询；此处保留原语义并标注风险
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `update_time`
FROM `user`
ORDER BY `update_time` DESC                                -- ⚠ filesort 风险：update_time 无索引
LIMIT 10;                                                  -- 最近变更的10个

-- ------------------------------------------------------------
-- 4.17 字段投影查询：仅查询用户名与头像（轻量列表）
-- 用途：仅需展示用户名与头像的场景，减少网络传输
-- 【优化点】ORDER BY username ASC 可走 uk_user_username 索引天然有序扫描，免 filesort；
--          WHERE is_disabled = 0 在回表后过滤；按需投影仅取 username/avatar 两列，减少网络与回表列读
-- ------------------------------------------------------------
SELECT `username`,
       `avatar`
FROM `user`
WHERE `is_disabled` = 0                                    -- 仅正常用户（回表后过滤）
ORDER BY `username` ASC;                                   -- 走 uk_user_username 有序，免 filesort

