-- 切换到目标数据库
USE `AIcode`;

-- ============================================================
-- 一、插入操作（Create）
-- ============================================================

-- ------------------------------------------------------------
-- 1.1 单条插入：新增一个用户（指定全部业务字段）
-- 用途：注册新用户时使用，用户名必须唯一否则违反唯一索引
-- 注意：password 字段应传入加密后的密文，不应存明文
-- ------------------------------------------------------------
INSERT INTO `user` (
    `avatar`,
    `username`,
    `password`,
    `preference`,
    `role_id`,
    `is_disabled`
) VALUES (
    'https://example.com/avatar/default.png',  -- 用户头像URL
    'zhangsan',                                 -- 用户名（唯一）
    '$2a$10$xxxxxxxxxxxxxxxxxxxxxxxxxxxx',      -- 密码密文（bcrypt 示例）
    '{"theme":"dark","lang":"zh-CN"}',          -- 用户喜好（JSON 字符串）
    1,                                          -- 角色ID
    0                                           -- 是否禁用：0-正常
);

-- ------------------------------------------------------------
-- 1.2 单条插入：仅必填字段（用户名 + 密码）
-- 用途：最小化注册场景，其余字段使用表默认值
-- ------------------------------------------------------------
INSERT INTO `user` (`username`, `password`)
VALUES ('lisi', 'encrypted_password_here');     -- 用户名、密码密文

-- ------------------------------------------------------------
-- 1.3 单条插入并返回自增主键
-- 用途：插入后需立即获取新用户ID（如关联写入其他表）
-- ------------------------------------------------------------
INSERT INTO `user` (`username`, `password`, `role_id`)
VALUES ('wangwu', 'encrypted_password_here', 2);

-- 获取刚刚插入的自增主键ID（与上一条 INSERT 配合使用）
SELECT LAST_INSERT_ID() AS `new_user_id`;

-- ------------------------------------------------------------
-- 1.4 批量插入：一次性新增多个用户
-- 用途：批量导入用户、初始化测试数据
-- 注意：任一 username 重复都会导致整批失败，建议事先校验或使用事务
-- ------------------------------------------------------------
INSERT INTO `user` (
    `avatar`,
    `username`,
    `password`,
    `preference`,
    `role_id`,
    `is_disabled`
) VALUES
    ('https://example.com/avatar/u1.png', 'user001', 'pwd_encrypted_1', NULL, 0, 0),
    ('https://example.com/avatar/u2.png', 'user002', 'pwd_encrypted_2', NULL, 0, 0),
    ('https://example.com/avatar/u3.png', 'user003', 'pwd_encrypted_3', '{"theme":"light"}', 3, 0),
    (NULL,                                  'user004', 'pwd_encrypted_4', NULL, 0, 1);

-- ------------------------------------------------------------
-- 1.5 插入或忽略：用户名已存在则跳过
-- 用途：批量导入时避免因重复用户名中断整批插入
-- ------------------------------------------------------------
INSERT IGNORE INTO `user` (`username`, `password`, `role_id`)
VALUES ('zhangsan', 'pwd_encrypted_new', 1);    -- 若 zhangsan 已存在则忽略

-- ------------------------------------------------------------
-- 1.6 插入或更新：用户名已存在则更新指定字段
-- 用途：upsert 场景，按 username 唯一键冲突时更新密码、头像、喜好等
-- ------------------------------------------------------------
INSERT INTO `user` (`username`, `password`, `avatar`, `preference`, `role_id`)
VALUES ('zhangsan', 'pwd_encrypted_new', 'https://example.com/avatar/new.png', '{"theme":"dark"}', 2)
ON DUPLICATE KEY UPDATE
    `password`   = VALUES(`password`),          -- 更新为待插入的密码
    `avatar`     = VALUES(`avatar`),            -- 更新为待插入的头像
    `preference` = VALUES(`preference`),        -- 更新为待插入的喜好
    `role_id`    = VALUES(`role_id`);           -- 更新为待插入的角色ID


-- ============================================================
-- 二、删除操作（Delete）
-- ============================================================

-- ------------------------------------------------------------
-- 2.1 按主键删除：删除指定ID的用户
-- 用途：根据用户ID删除单个用户
-- 注意：生产环境建议改为"软删除"（更新 is_disabled=1），物理删除需谨慎
-- ------------------------------------------------------------
DELETE FROM `user`
WHERE `id` = 1;                                 -- 待删除的用户主键ID

-- ------------------------------------------------------------
-- 2.2 按主键批量删除：删除多个指定ID的用户
-- 用途：批量删除用户（如后台管理勾选多个用户后批量删除）
-- ------------------------------------------------------------
DELETE FROM `user`
WHERE `id` IN (10, 11, 12, 13, 14);             -- 待删除的用户主键ID列表

-- ------------------------------------------------------------
-- 2.3 按用户名删除：删除指定用户名的用户
-- 用途：按登录账号删除用户
-- ------------------------------------------------------------
DELETE FROM `user`
WHERE `username` = 'zhangsan';                  -- 待删除的用户名

-- ------------------------------------------------------------
-- 2.4 按条件删除：删除某角色下所有已禁用用户
-- 用途：清理某角色下被禁用的账号
-- ------------------------------------------------------------
DELETE FROM `user`
WHERE `role_id` = 3                              -- 指定角色ID
  AND `is_disabled` = 1;                         -- 且已被禁用

-- ------------------------------------------------------------
-- 2.5 按条件删除：删除创建时间早于指定日期的所有用户
-- 用途：清理历史脏数据或过期账号
-- 注意：执行前建议先用 SELECT 确认影响范围
-- ------------------------------------------------------------
DELETE FROM `user`
WHERE `create_time` < '2020-01-01 00:00:00';    -- 创建时间早于该时间点的用户

-- ------------------------------------------------------------
-- 2.6 清空全表（慎用）
-- 用途：仅用于测试环境重置数据，生产环境严禁使用
-- 注意：TRUNCATE 会重置 AUTO_INCREMENT，且无法事务回滚
-- ------------------------------------------------------------
-- TRUNCATE TABLE `user`;                       -- 取消注释后执行，将清空全部用户数据


-- ============================================================
-- 三、修改操作（Update）
-- ============================================================

-- ------------------------------------------------------------
-- 3.1 按主键修改：更新指定用户的基本信息
-- 用途：编辑用户资料（头像、喜好、角色）
-- 注意：update_time 由 ON UPDATE 自动维护，无需手动赋值
-- ------------------------------------------------------------
UPDATE `user`
SET `avatar`     = 'https://example.com/avatar/new.png',  -- 新头像URL
    `preference` = '{"theme":"dark","lang":"en"}',        -- 新喜好设置
    `role_id`    = 2                                       -- 新角色ID
WHERE `id` = 1;                                            -- 目标用户主键ID

-- ------------------------------------------------------------
-- 3.2 按主键修改密码：更新指定用户的密码
-- 用途：用户修改密码 / 管理员重置密码
-- 注意：应传入加密后的密文
-- ------------------------------------------------------------
UPDATE `user`
SET `password` = '$2a$10$yyyyyyyyyyyyyyyyyyyyyyyy'        -- 新密码密文
WHERE `id` = 1;                                            -- 目标用户主键ID

-- ------------------------------------------------------------
-- 3.3 按主键修改状态：禁用 / 启用指定用户
-- 用途：管理员封禁或解封用户账号
-- ------------------------------------------------------------
UPDATE `user`
SET `is_disabled` = 1                                      -- 1-禁用，0-启用
WHERE `id` = 1;                                            -- 目标用户主键ID

-- ------------------------------------------------------------
-- 3.4 按主键批量修改状态：批量禁用多个用户
-- 用途：后台批量封禁
-- ------------------------------------------------------------
UPDATE `user`
SET `is_disabled` = 1                                      -- 1-禁用
WHERE `id` IN (10, 11, 12);                                -- 目标用户主键ID列表

-- ------------------------------------------------------------
-- 3.5 按条件修改：将某角色下所有用户切换到新角色
-- 用途：角色调整 / 权限迁移
-- ------------------------------------------------------------
UPDATE `user`
SET `role_id` = 5                                          -- 新角色ID
WHERE `role_id` = 3                                        -- 原角色ID
  AND `is_disabled` = 0;                                   -- 仅更新正常用户

-- ------------------------------------------------------------
-- 3.6 按条件修改：禁用某时间点之前注册的用户
-- 用途：长期未活跃账号批量封禁
-- ------------------------------------------------------------
UPDATE `user`
SET `is_disabled` = 1                                      -- 1-禁用
WHERE `create_time` < '2023-01-01 00:00:00'                -- 创建时间早于该时间点
  AND `is_disabled` = 0;                                   -- 且当前为正常状态

-- ------------------------------------------------------------
-- 3.7 按用户名修改头像：根据用户名更新头像
-- 用途：用户在前台自行更换头像
-- ------------------------------------------------------------
UPDATE `user`
SET `avatar` = 'https://example.com/avatar/updated.png'    -- 新头像URL
WHERE `username` = 'zhangsan';                             -- 目标用户名


-- ============================================================
-- 四、查询操作（Read）
-- ============================================================

-- ------------------------------------------------------------
-- 4.1 单条查询：按主键ID查询用户全部字段
-- 用途：根据用户ID获取用户详细信息
-- ------------------------------------------------------------
SELECT *
FROM `user`
WHERE `id` = 1;                                            -- 目标用户主键ID

-- ------------------------------------------------------------
-- 4.2 单条查询：按用户名查询用户（登录校验场景）
-- 用途：登录时根据用户名获取账号信息（含密码密文用于比对）
-- 注意：命中唯一索引，查询效率高
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `password`,
       `avatar`,
       `role_id`,
       `is_disabled`,
       `create_time`,
       `update_time`
FROM `user`
WHERE `username` = 'zhangsan'                              -- 登录用户名
LIMIT 1;                                                   -- 限制单条

-- ------------------------------------------------------------
-- 4.3 单条查询：仅返回用户ID是否存在（存在性校验）
-- 用途：注册时校验用户名是否已被占用
-- ------------------------------------------------------------
SELECT `id`
FROM `user`
WHERE `username` = 'zhangsan'                              -- 待校验的用户名
LIMIT 1;

-- ------------------------------------------------------------
-- 4.4 列表查询：查询全部用户（带返回字段裁剪）
-- 用途：用户管理列表页展示
-- 注意：生产环境应避免无 LIMIT 的全表查询，此处仅作示例
-- ------------------------------------------------------------
SELECT `id`,
       `avatar`,
       `username`,
       `role_id`,
       `is_disabled`,
       `create_time`
FROM `user`
ORDER BY `id` ASC;                                         -- 按主键升序排列

-- ------------------------------------------------------------
-- 4.5 列表查询：查询所有正常（未禁用）用户
-- 用途：获取有效账号列表
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `role_id`,
       `create_time`
FROM `user`
WHERE `is_disabled` = 0                                    -- 0-正常
ORDER BY `create_time` DESC;                               -- 按创建时间倒序

-- ------------------------------------------------------------
-- 4.6 分页查询：按页码查询用户列表
-- 用途：后台分页展示用户列表
-- 参数说明：page_index 为页码（从1开始），page_size 为每页条数
-- 示例：查询第 2 页，每页 10 条 → LIMIT 10 OFFSET 10
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `role_id`,
       `is_disabled`,
       `create_time`
FROM `user`
ORDER BY `id` ASC                                          -- 按主键升序
LIMIT 10 OFFSET 10;                                        -- 每页10条，跳过前10条（第2页）

-- ------------------------------------------------------------
-- 4.7 分页查询：按条件分页查询某角色下的正常用户
-- 用途：角色管理页中查看某角色下的用户（分页）
-- 命中复合索引 idx_user_role_disabled，查询效率高
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `create_time`
FROM `user`
WHERE `role_id` = 2                                        -- 指定角色ID
  AND `is_disabled` = 0                                    -- 仅正常用户
ORDER BY `create_time` DESC                                -- 按创建时间倒序
LIMIT 20 OFFSET 0;                                         -- 每页20条，第1页

-- ------------------------------------------------------------
-- 4.8 条件查询：按用户名模糊查询
-- 用途：后台搜索用户（支持用户名关键字检索）
-- 注意：LIKE '%xxx%' 无法走索引，数据量大时建议改用全文索引或 ES
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `role_id`,
       `is_disabled`
FROM `user`
WHERE `username` LIKE '%zhang%'                            -- 用户名包含 zhang
ORDER BY `id` ASC
LIMIT 50;                                                  -- 限制最多返回50条

-- ------------------------------------------------------------
-- 4.9 条件查询：多条件组合查询（角色 + 状态 + 时间范围）
-- 用途：后台高级筛选用户
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `role_id`,
       `is_disabled`,
       `create_time`,
       `update_time`
FROM `user`
WHERE `role_id` = 2                                        -- 指定角色ID
  AND `is_disabled` = 0                                    -- 仅正常用户
  AND `create_time` BETWEEN '2024-01-01 00:00:00'          -- 创建时间范围起
                              AND '2024-12-31 23:59:59'    -- 创建时间范围止
ORDER BY `create_time` DESC
LIMIT 100;                                                 -- 限制最多返回100条

-- ------------------------------------------------------------
-- 4.10 条件查询：按用户ID集合批量查询
-- 用途：根据一批用户ID获取用户信息（如批量展示用户昵称头像）
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`
FROM `user`
WHERE `id` IN (1, 2, 3, 5, 8, 13);                         -- 用户ID集合

-- ------------------------------------------------------------
-- 4.11 聚合统计：统计用户总数
-- 用途：仪表盘展示用户总量
-- ------------------------------------------------------------
SELECT COUNT(*) AS `total_count`                           -- 用户总数
FROM `user`;

-- ------------------------------------------------------------
-- 4.12 聚合统计：按状态分组统计用户数量
-- 用途：统计正常 / 禁用用户数
-- ------------------------------------------------------------
SELECT `is_disabled` AS `status`,                          -- 账号状态：0-正常，1-禁用
       COUNT(*)     AS `count`                             -- 对应数量
FROM `user`
GROUP BY `is_disabled`;

-- ------------------------------------------------------------
-- 4.13 聚合统计：按角色分组统计用户数量
-- 用途：统计每个角色下的用户数
-- ------------------------------------------------------------
SELECT `role_id`    AS `role_id`,                          -- 角色ID
       COUNT(*)    AS `user_count`                         -- 该角色下用户数
FROM `user`
GROUP BY `role_id`
ORDER BY `user_count` DESC;                                -- 按用户数倒序

-- ------------------------------------------------------------
-- 4.14 聚合统计：按角色分组统计正常用户数量
-- 用途：统计每个角色下有效账号数
-- ------------------------------------------------------------
SELECT `role_id`    AS `role_id`,                          -- 角色ID
       COUNT(*)    AS `active_count`                       -- 该角色下正常用户数
FROM `user`
WHERE `is_disabled` = 0                                    -- 仅统计正常用户
GROUP BY `role_id`;

-- ------------------------------------------------------------
-- 4.15 排序查询：查询最近注册的 N 个用户
-- 用途：展示最新注册用户
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `create_time`
FROM `user`
ORDER BY `create_time` DESC                                -- 按创建时间倒序
LIMIT 10;                                                  -- 最近10个

-- ------------------------------------------------------------
-- 4.16 排序查询：查询最近更新的 N 个用户
-- 用途：展示近期有变更的用户
-- ------------------------------------------------------------
SELECT `id`,
       `username`,
       `avatar`,
       `update_time`
FROM `user`
ORDER BY `update_time` DESC                                -- 按更新时间倒序
LIMIT 10;                                                  -- 最近变更的10个

-- ------------------------------------------------------------
-- 4.17 字段投影查询：仅查询用户名与头像（轻量列表）
-- 用途：仅需展示用户名与头像的场景，减少网络传输
-- ------------------------------------------------------------
SELECT `username`,
       `avatar`
FROM `user`
WHERE `is_disabled` = 0                                    -- 仅正常用户
ORDER BY `username` ASC;                                   -- 按用户名升序

-- ------------------------------------------------------------
-- 4.18 存在性查询：判断指定用户名是否存在
-- 用途：注册前校验用户名占用情况，使用 EXISTS 性能优于 SELECT *
-- ------------------------------------------------------------
SELECT EXISTS(
    SELECT 1
    FROM `user`
    WHERE `username` = 'zhangsan'                          -- 待校验的用户名
) AS `is_exists`;                                          -- 1-存在，0-不存在

