-- 文件名称：user_op.sql
-- 功能描述：user 用户表的增删改查（CRUD）操作脚本
-- 依赖对象：AIcode 数据库下的 user 表（由 user.sql 创建）
-- 备注说明：所有 SQL 均针对 `AIcode`.`user` 表，语句前均附中文用途说明
